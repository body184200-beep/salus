import PDFDocument from 'pdfkit';
import { db } from '../db/database.js';

export interface ReportData {
  reportId: string;
  generatedAt: string;
  patientPseudonym: string;
  ageRange?: string;
  medications: Array<{
    name: string;
    dosage?: string;
    frequency?: string;
    startDate?: string;
  }>;
  symptoms: Array<{
    symptomName: string;
    startDate: string;
    severity: string;
    duration?: string;
    isOngoing: boolean;
    impactDailyActivities: boolean;
    impactBalance: boolean;
    impactWalking: boolean;
    impactMobility: boolean;
    fatigueDuringActivities: boolean;
    notes?: string;
  }>;
  pharmacistConsultationNotes?: string;
  disclaimerEn: string;
  disclaimerAr: string;
}

export function compileReportData(patientId: string): ReportData {
  const patient = db.prepare('SELECT id, display_name FROM users WHERE id = ?').get(patientId) as any;
  const profile = db.prepare('SELECT age_range FROM patient_profiles WHERE user_id = ?').get(patientId) as any;

  const meds = db.prepare(`
    SELECT pm.*, p.brand_name_en, p.brand_name_ar, a.name_en as active_name_en, a.name_ar as active_name_ar
    FROM patient_medications pm
    LEFT JOIN medication_products p ON pm.medication_product_id = p.id
    LEFT JOIN active_ingredients a ON pm.active_ingredient_id = a.id
    WHERE pm.user_id = ? AND pm.is_active = 1
  `).all(patientId) as any[];

  const symptoms = db.prepare(`
    SELECT * FROM symptom_logs
    WHERE user_id = ?
    ORDER BY start_date DESC
  `).all(patientId) as any[];

  // Get most recent completed or in_review pharmacist follow-up note
  const followUp = db.prepare(`
    SELECT pharmacist_notes FROM follow_up_requests
    WHERE patient_id = ? AND pharmacist_notes IS NOT NULL
    ORDER BY updated_at DESC LIMIT 1
  `).get(patientId) as any;

  return {
    reportId: 'SALUS-REP-' + Date.now().toString().slice(-6),
    generatedAt: new Date().toISOString(),
    patientPseudonym: patient ? patient.display_name : 'Anonymous Patient',
    ageRange: profile ? profile.age_range : 'Not specified',
    medications: meds.map((m) => ({
      name: m.custom_name || m.brand_name_en || m.active_name_en || 'Medication',
      dosage: m.dosage || undefined,
      frequency: m.frequency || undefined,
      startDate: m.start_date || undefined,
    })),
    symptoms: symptoms.map((s) => ({
      symptomName: s.symptom_name,
      startDate: s.start_date,
      severity: s.severity,
      duration: s.duration || undefined,
      isOngoing: s.is_ongoing === 1,
      impactDailyActivities: s.impact_daily_activities === 1,
      impactBalance: s.impact_balance === 1,
      impactWalking: s.impact_walking === 1,
      impactMobility: s.impact_mobility === 1,
      fatigueDuringActivities: s.fatigue_during_activities === 1,
      notes: s.notes || undefined,
    })),
    pharmacistConsultationNotes: followUp ? followUp.pharmacist_notes : undefined,
    disclaimerEn:
      'CRITICAL MEDICAL DISCLAIMER: This document is an informational patient summary generated by SALUS for communication purposes between the patient and licensed healthcare professionals. It does NOT constitute a medical diagnosis, clinical prognosis, or prescription. Never alter or discontinue medications without direct physician consultation.',
    disclaimerAr:
      'إخلاء مسؤولية طبي هام: هذا التقرير هو ملخص معلوماتي مُنشأ عبر منصة سالوس لتسهيل التواصل بين المريض ومقدمي الرعاية الصحية المرخصين. هذا التقرير لا يمثل تشخيصاً طبياً ولا استشارة علاجية نهائية. يحظر تغيير أو إيقاف الأدوية دون استشارة مباشرة من الطبيب المعالج.',
  };
}

export function generatePdfReport(data: ReportData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 40, size: 'A4' });
      const buffers: Buffer[] = [];

      doc.on('data', buffers.push.bind(buffers));
      doc.on('end', () => {
        const pdfData = Buffer.concat(buffers);
        resolve(pdfData);
      });

      // Header Brand
      doc.fillColor('#087D69').fontSize(22).font('Helvetica-Bold').text('SALUS | سالوس', { align: 'left' });
      doc.fillColor('#60756D').fontSize(10).font('Helvetica').text('Know Your Medicine. Stay Safer. | Clinical Medication & Symptom Report', { align: 'left' });
      doc.moveDown(0.5);

      // Horizontal separator
      doc.strokeColor('#087D69').lineWidth(1.5).moveTo(40, doc.y).lineTo(550, doc.y).stroke();
      doc.moveDown(1);

      // Meta Info Card
      doc.fillColor('#183B35').fontSize(12).font('Helvetica-Bold').text('Patient Information:');
      doc.fontSize(10).font('Helvetica')
        .text(`Report ID: ${data.reportId}`)
        .text(`Generated Date: ${new Date(data.generatedAt).toLocaleDateString()} ${new Date(data.generatedAt).toLocaleTimeString()}`)
        .text(`Patient Pseudonym: ${data.patientPseudonym}`)
        .text(`Age Range: ${data.ageRange}`);
      doc.moveDown(1);

      // Medications Section
      doc.fillColor('#087D69').fontSize(14).font('Helvetica-Bold').text('Current Active Medications:');
      doc.moveDown(0.3);

      if (data.medications.length === 0) {
        doc.fillColor('#60756D').fontSize(10).font('Helvetica-Oblique').text('No active medications currently registered.');
      } else {
        data.medications.forEach((m, idx) => {
          doc.fillColor('#183B35').fontSize(10).font('Helvetica-Bold').text(`${idx + 1}. ${m.name}`);
          let details = '';
          if (m.dosage) details += `Dosage: ${m.dosage} | `;
          if (m.frequency) details += `Frequency: ${m.frequency} | `;
          if (m.startDate) details += `Started: ${m.startDate}`;
          if (details) {
            doc.fillColor('#60756D').fontSize(9).font('Helvetica').text(`   ${details}`);
          }
          doc.moveDown(0.2);
        });
      }
      doc.moveDown(1);

      // Symptoms Log Timeline
      doc.fillColor('#087D69').fontSize(14).font('Helvetica-Bold').text('Recorded Symptom History & Functional Impact:');
      doc.moveDown(0.3);

      if (data.symptoms.length === 0) {
        doc.fillColor('#60756D').fontSize(10).font('Helvetica-Oblique').text('No symptoms reported during this recording interval.');
      } else {
        data.symptoms.forEach((s, idx) => {
          doc.fillColor('#183B35').fontSize(10).font('Helvetica-Bold').text(`${idx + 1}. ${s.symptomName} [Severity: ${s.severity.toUpperCase()}]`);
          let meta = `Started: ${s.startDate} | Status: ${s.isOngoing ? 'Ongoing' : 'Resolved'}`;
          if (s.duration) meta += ` | Duration: ${s.duration}`;
          doc.fillColor('#60756D').fontSize(9).font('Helvetica').text(`   ${meta}`);

          // Mobility & Physiotherapy impact
          const functionalImpacts: string[] = [];
          if (s.impactDailyActivities) functionalImpacts.push('Daily Activities');
          if (s.impactBalance) functionalImpacts.push('Balance');
          if (s.impactWalking) functionalImpacts.push('Walking');
          if (s.impactMobility) functionalImpacts.push('General Mobility');
          if (s.fatigueDuringActivities) functionalImpacts.push('Exertional Fatigue');

          if (functionalImpacts.length > 0) {
            doc.fillColor('#B42318').fontSize(8.5).font('Helvetica-Bold').text(`   Physiotherapy/Mobility Impact: ${functionalImpacts.join(', ')}`);
          }

          if (s.notes) {
            doc.fillColor('#183B35').fontSize(8.5).font('Helvetica-Oblique').text(`   Patient Observation: "${s.notes}"`);
          }
          doc.moveDown(0.4);
        });
      }
      doc.moveDown(1);

      // Pharmacist Clinical Note
      if (data.pharmacistConsultationNotes) {
        doc.fillColor('#174D49').fontSize(12).font('Helvetica-Bold').text('Licensed Pharmacist Clinical Review Note:');
        doc.fillColor('#183B35').fontSize(9.5).font('Helvetica').text(data.pharmacistConsultationNotes);
        doc.moveDown(1);
      }

      // Disclaimer Box
      doc.moveDown(1);
      doc.strokeColor('#B42318').lineWidth(1).rect(40, doc.y, 510, 65).stroke();
      doc.fillColor('#B42318').fontSize(9).font('Helvetica-Bold').text('CRITICAL MEDICAL DISCLAIMER', 45, doc.y + 6);
      doc.fillColor('#183B35').fontSize(7.5).font('Helvetica').text(data.disclaimerEn, 45, doc.y + 3, { width: 500 });

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}
